-- Application tables, exactly as supplied by the challenge, plus integrity
-- constraints and a non-unique lookup index. Safe to re-run.

CREATE TABLE IF NOT EXISTS app.firms (
    id            INTEGER PRIMARY KEY,
    name          TEXT    NOT NULL,
    balance_cents INTEGER NOT NULL CONSTRAINT firms_balance_nonnegative CHECK (balance_cents >= 0),
    uuid          TEXT    NOT NULL
        CONSTRAINT firms_uuid_key UNIQUE
        CONSTRAINT firms_uuid_format
            CHECK (uuid ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$')
);

CREATE TABLE IF NOT EXISTS app.payments (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payer_firm_id INTEGER NOT NULL REFERENCES app.firms (id),
    payee_firm_id INTEGER NOT NULL REFERENCES app.firms (id),
    amount_cents  INTEGER NOT NULL CONSTRAINT payments_amount_positive CHECK (amount_cents > 0),
    description   TEXT    NOT NULL
);

-- Lookup for the conditional idempotency key (payer, payee, exact description).
-- Deliberately not unique: OFF mode stores repeated keys.
CREATE INDEX IF NOT EXISTS payments_key_idx
    ON app.payments (payer_firm_id, payee_firm_id, (description COLLATE "C"));
